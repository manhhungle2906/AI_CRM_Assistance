// Helper functions
export function getCustomerById(id: string): Customer | undefined {
  return mockCustomers.find((c) => c.id === id);
}

export function getCustomersBySegment(segment: CustomerSegment): Customer[] {
  return mockCustomers.filter((c) => c.segment === segment);
}

export function getCustomersByMicroSegment(microSegment: MicroSegment): Customer[] {
  return mockCustomers.filter((c) => c.microSegment === microSegment);
}

export function getCustomersByRM(rmId: string): Customer[] {
  return mockCustomers.filter((c) => c.assignedRMId === rmId);
}

export function getHighPriorityCustomers(): Customer[] {
  return mockCustomers
    .filter((c) => c.opportunityScore >= 70)
    .sort((a, b) => b.opportunityScore - a.opportunityScore)
    .slice(0, 10);
}

export function getRetentionRiskCustomers(): Customer[] {
  return mockCustomers
    .filter((c) => c.churnRiskScore >= 50)
    .sort((a, b) => b.churnRiskScore - a.churnRiskScore);
}

export function getComplaintCustomers(): Customer[] {
  return mockCustomers.filter((c) => c.complaintStatus === 'Open');
}

export function getRiskCustomers(): Customer[] {
  return mockCustomers
    .filter((c) => c.creditRiskScore >= 40 || c.fraudSignalScore >= 15)
    .sort((a, b) => b.creditRiskScore - a.creditRiskScore);
}

export function getLoanRenewalDueCustomers(): Customer[] {
  return mockCustomers.filter((c) => c.nextRenewalDate !== undefined);
}

export function getDormantCustomers(): Customer[] {
  return mockCustomers.filter((c) => c.transactionTrend3M < -10 || c.lastInteractionDate < '2026-03-01');
}

export function getLowDigitalAdoptionCustomers(): Customer[] {
  return mockCustomers.filter((c) => c.digitalAdoptionScore < 40);
}

export function searchCustomers(query: string): Customer[] {
  const lowerQuery = query.toLowerCase();
  return mockCustomers.filter(
    (c) =>
      c.name.toLowerCase().includes(lowerQuery) ||
      c.segment.toLowerCase().includes(lowerQuery) ||
      c.microSegment.toLowerCase().includes(lowerQuery) ||
      c.industry?.toLowerCase().includes(lowerQuery) ||
      c.region.toLowerCase().includes(lowerQuery)
  );
}

export function getSegmentDistribution(): { name: string; value: number; color: string }[] {
  const counts: Record<string, number> = {};
  mockCustomers.forEach((c) => {
    counts[c.segment] = (counts[c.segment] || 0) + 1;
  });
  
  const colors: Record<string, string> = {
    Individual: '#0EA5E9',
    SME: '#0369A1',
    Corporate: '#075985',
    Priority: '#0284C7',
    Mass: '#0C4A6E',
    Affluent: '#06B6D4',
  };
  
  return Object.entries(counts).map(([name, value]) => ({
    name,
    value,
    color: colors[name] || '#0EA5E9',
  }));
}

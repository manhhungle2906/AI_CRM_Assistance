// Helper functions
export function getCampaignById(id: string): Campaign | undefined {
  return mockCampaigns.find((c) => c.id === id);
}

export function getActiveCampaigns(): Campaign[] {
  return mockCampaigns.filter((c) => c.status === 'Active');
}

export function getCampaignsByProduct(productId: string): Campaign[] {
  return mockCampaigns.filter((c) => c.productId === productId);
}

export function getTopPerformingCampaigns(): Campaign[] {
  return [...mockCampaigns]
    .sort((a, b) => b.conversionRate - a.conversionRate)
    .slice(0, 5);
}

export function getCampaignSummary(): {
  totalCampaigns: number;
  activeCampaigns: number;
  totalLeads: number;
  totalConversions: number;
  avgConversionRate: number;
  totalRevenueEstimate: number;
} {
  const active = getActiveCampaigns();
  const totalLeads = mockCampaigns.reduce((sum, c) => sum + c.leadsGenerated, 0);
  const totalConversions = mockCampaigns.reduce((sum, c) => sum + c.conversions, 0);
  const avgConversionRate = mockCampaigns.reduce((sum, c) => sum + c.conversionRate, 0) / mockCampaigns.length;
  const totalRevenue = mockCampaigns.reduce((sum, c) => sum + c.revenueEstimate, 0);

  return {
    totalCampaigns: mockCampaigns.length,
    activeCampaigns: active.length,
    totalLeads,
    totalConversions,
    avgConversionRate,
    totalRevenueEstimate: totalRevenue,
  };
}
